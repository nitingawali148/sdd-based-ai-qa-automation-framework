"""Flow 1 - Specification Flow.

Requirement Input -> Requirement Analysis -> Specification Generation -> Specification Validation
-> Human Approval (gate) -> Approved Specification
"""

from __future__ import annotations

from crewai.flow.flow import Flow, listen, or_, router, start

from core.artifact_manager import ArtifactManager
from core.logger import audit
from core.state import SpecificationFlowState
from flows import stages
from versioning.version_manager import VersionManager


class SpecificationFlow(Flow[SpecificationFlowState]):
    @start()
    def ingest_and_specify(self) -> str:
        spec, generated = stages.generate_specification(self.state.requirement_id, self.state.regenerate)
        self.state.spec_id = spec.id
        am = ArtifactManager()
        self.state.artifacts["spec"] = str(am.spec_dir(spec.id) / "spec.md")
        self.state.message = ("Specification generated by the Requirement Analysis and Specification Architect "
                              "agents" if generated else "Existing working specification reused (human edits kept)")
        return spec.id

    @listen(ingest_and_specify)
    def validate(self) -> bool:
        report = stages.validate_specification(self.state.spec_id)
        self.state.findings = [f.model_dump() for f in report.findings if f.severity != "info"]
        self.state.artifacts["validation_report"] = str(ArtifactManager().path_of(self.state.spec_id, "validation"))
        return report.passed

    @router(validate)
    def approval_gate(self) -> str:
        report = ArtifactManager().load(self.state.spec_id, "validation")
        if not report.passed:
            self.state.gate("spec_validation", "BLOCKED", f"{len(report.errors)} blocking finding(s)")
            return "needs_clarification"
        self.state.gate("spec_validation", "PASSED")
        if VersionManager().spec_is_approved(self.state.spec_id):
            self.state.gate("human_spec_approval", "PASSED")
            return "spec_approved"
        self.state.gate("human_spec_approval", "AWAITING_APPROVAL")
        return "awaiting_spec_approval"

    @listen("needs_clarification")
    def request_clarification(self) -> None:
        self.state.status = "NEEDS_CLARIFICATION"
        self.state.artifacts["clarification_request"] = str(
            ArtifactManager().spec_dir(self.state.spec_id) / "clarification_request.md")
        self.state.next_action = ("Resolve the items in clarification_request.md (update the requirement and run "
                                  f"`python main.py spec {self.state.requirement_id} --regenerate`, or edit the spec YAML "
                                  "and run this flow again)")

    @listen("awaiting_spec_approval")
    def request_approval(self) -> None:
        self.state.status = "AWAITING_SPEC_APPROVAL"
        self.state.next_action = (f"Review {self.state.artifacts['spec']} then run: python main.py approve "
                                  f"{self.state.spec_id} --stage spec --by \"<your name>\"")

    @listen(or_("spec_approved", request_approval, request_clarification))
    def finish(self) -> SpecificationFlowState:
        if self.state.status == "STARTED":
            self.state.status = "SPEC_APPROVED"
        audit.write("flow", flow="specification", spec_id=self.state.spec_id, status=self.state.status)
        return self.state
